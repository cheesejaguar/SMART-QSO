#!/usr/bin/env python3
"""
Generate the uplink command dictionary for flight and ground software.

Source:  software/flight/command_dictionary.json
Outputs: software/flight/include/cmd_dictionary.h
         software/rust/sqso-protocol/src/dictionary.rs
         software/ground/tools/command_dictionary.py

Usage:
    python3 scripts/gen_command_dictionary.py           # write the outputs
    python3 scripts/gen_command_dictionary.py --check   # fail if any output is stale (CI)
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "software" / "flight" / "command_dictionary.json"
OUT_H = REPO / "software" / "flight" / "include" / "cmd_dictionary.h"
OUT_RS = REPO / "software" / "rust" / "sqso-protocol" / "src" / "dictionary.rs"
OUT_PY = REPO / "software" / "ground" / "tools" / "command_dictionary.py"

MAX_ARGS = 64
KEYS = {"operational": "CMD_KEY_OPERATIONAL", "recovery": "CMD_KEY_RECOVERY", "any": "CMD_KEY_ANY"}
BANNER = "GENERATED by scripts/gen_command_dictionary.py from software/flight/command_dictionary.json. Do not edit."


def validate(data: Dict) -> List[Dict]:
    """Return the command list in ID order, or raise ValueError."""
    commands = []
    seen_ids, seen_names = set(), set()
    for raw in data["commands"]:
        name = raw["name"]
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            raise ValueError(f"{name}: name must be upper-case")
        if not re.fullmatch(r"CMD_[A-Z0-9_]+", raw["c_name"]):
            raise ValueError(f"{name}: c_name must be a CMD_* enum symbol")
        cmd_id = int(raw["id"], 16)
        if not 0 <= cmd_id <= 0xFF:
            raise ValueError(f"{name}: id must fit in one byte")
        lo, hi = raw["min_args"], raw["max_args"]
        if not 0 <= lo <= hi <= MAX_ARGS:
            raise ValueError(f"{name}: args must satisfy 0 <= min <= max <= {MAX_ARGS}")
        if raw["key"] not in KEYS:
            raise ValueError(f"{name}: key must be one of {sorted(KEYS)}")
        without_key = bool(raw.get("without_key", False))
        if without_key and raw["key"] != "any":
            raise ValueError(f"{name}: without_key is only allowed with key 'any'")
        if cmd_id in seen_ids or name in seen_names or rust_variant(name) in seen_names:
            raise ValueError(f"{name}: duplicate id or name")
        seen_ids.add(cmd_id)
        seen_names.update((name, rust_variant(name)))
        commands.append({**raw, "cmd_id": cmd_id, "without_key": without_key})
    return sorted(commands, key=lambda c: c["cmd_id"])


def rust_variant(name: str) -> str:
    """SET_CONTACT_TIMEOUT -> SetContactTimeout"""
    return "".join(part.capitalize() for part in name.split("_"))


def render_h(commands: List[Dict]) -> str:
    ids = "\n".join(
        f"    {c['c_name']} = 0x{c['cmd_id']:02X}, /**< {c['name']}: {c['summary']} */"
        for c in commands)
    return f"""/**
 * @file cmd_dictionary.h
 * @brief Uplink command dictionary (SQSO-ICD-013 section 7)
 *
 * {BANNER}
 *
 * The table g_cmd_dictionary is defined by the Rust protocol crate
 * (software/rust/sqso-protocol, generated from the same source), so the
 * C and Rust views of the dictionary cannot differ.
 */

#ifndef SMART_QSO_CMD_DICTIONARY_H
#define SMART_QSO_CMD_DICTIONARY_H

#ifdef __cplusplus
extern "C" {{
#endif

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/** Command IDs in the dictionary */
typedef enum {{
{ids}
}} CmdId_t;

/** Number of commands in the dictionary */
#define CMD_DICTIONARY_COUNT {len(commands)}U

/** Which telecommand key authenticates a command */
typedef enum {{
    CMD_KEY_OPERATIONAL = 0, /**< Active operational key */
    CMD_KEY_RECOVERY    = 1, /**< Offline recovery key */
    CMD_KEY_ANY         = 2  /**< Either key */
}} CmdKeyClass_t;

/** One dictionary entry */
typedef struct {{
    uint8_t cmd_id;          /**< Command ID */
    uint8_t min_args;        /**< Minimum argument bytes */
    uint8_t max_args;        /**< Maximum argument bytes */
    CmdKeyClass_t key;       /**< Authenticating key */
    bool without_key;        /**< Accepted unauthenticated when no key is usable */
}} CmdDictEntry_t;

/** The dictionary, in command-ID order */
extern const CmdDictEntry_t g_cmd_dictionary[];

/** Number of entries in g_cmd_dictionary */
extern const size_t g_cmd_dictionary_count;

#ifdef __cplusplus
}}
#endif

#endif /* SMART_QSO_CMD_DICTIONARY_H */
"""


def render_rust(commands: List[Dict]) -> str:
    keys = {"operational": "Operational", "recovery": "Recovery", "any": "Any"}
    variants = "\n".join(
        f"    /// {c['summary']}\n    {rust_variant(c['name'])} = 0x{c['cmd_id']:02X},"
        for c in commands)
    all_list = ",\n".join(f"        Command::{rust_variant(c['name'])}" for c in commands)
    from_id = "\n".join(
        f"            0x{c['cmd_id']:02X} => Some(Command::{rust_variant(c['name'])}),"
        for c in commands)
    names = "\n".join(
        f"            Command::{rust_variant(c['name'])} => c\"{c['name']}\","
        for c in commands)
    specs = "\n".join(
        f"            Command::{rust_variant(c['name'])} => CommandSpec {{ min_args: {c['min_args']}, "
        f"max_args: {c['max_args']}, key: KeyClass::{keys[c['key']]}, "
        f"without_key: {'true' if c['without_key'] else 'false'} }},"
        for c in commands)
    summaries = "\n".join(
        f"            Command::{rust_variant(c['name'])} => {json.dumps(c['summary'])},"
        for c in commands)
    return f"""//! Uplink command dictionary (SQSO-ICD-013 section 7).
//!
//! {BANNER}

use core::ffi::CStr;

use crate::command::{{CommandSpec, KeyClass}};

/// Every uplink command in the dictionary. Adding one to
/// `command_dictionary.json` adds a variant here, and every exhaustive
/// `match` on `Command` (the flight dispatcher among them) stops compiling
/// until it is handled.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[repr(u8)]
pub enum Command {{
{variants}
}}

impl Command {{
    /// Every command, in ID order
    pub const ALL: [Command; {len(commands)}] = [
{all_list},
    ];

    /// The command with this ID, if the dictionary has one
    pub const fn from_id(id: u8) -> Option<Command> {{
        match id {{
{from_id}
            _ => None,
        }}
    }}

    /// Command ID on the uplink
    pub const fn id(self) -> u8 {{
        self as u8
    }}

    /// Dictionary name
    pub const fn name(self) -> &'static str {{
        match self.c_name().to_str() {{
            Ok(name) => name,
            Err(_) => "",
        }}
    }}

    /// Dictionary name, NUL-terminated for C
    pub const fn c_name(self) -> &'static CStr {{
        match self {{
{names}
        }}
    }}

    /// Argument bounds and authenticating key
    pub const fn spec(self) -> CommandSpec {{
        match self {{
{specs}
        }}
    }}

    /// One-line description
    pub const fn summary(self) -> &'static str {{
        match self {{
{summaries}
        }}
    }}
}}
"""


def render_python(commands: List[Dict]) -> str:
    rows = "\n".join(
        f'    "{c["name"]}": CommandSpec({c["cmd_id"]:#04x}, {c["min_args"]}, {c["max_args"]}, '
        f'"{c["key"]}", {json.dumps(c["summary"])}, without_key={c["without_key"]}),'
        for c in commands)
    return f'''"""
Uplink command dictionary (SQSO-ICD-013 section 7).

{BANNER}
"""

from dataclasses import dataclass
from typing import Dict


@dataclass(frozen=True)
class CommandSpec:
    """One command: ID, allowed argument bytes, authenticating key."""
    cmd_id: int
    min_args: int
    max_args: int
    key: str
    summary: str
    without_key: bool = False


COMMANDS: Dict[str, CommandSpec] = {{
{rows}
}}
'''


def outputs() -> Dict[Path, str]:
    commands = validate(json.loads(SOURCE.read_text()))
    return {OUT_H: render_h(commands), OUT_RS: render_rust(commands), OUT_PY: render_python(commands)}


def check() -> List[Path]:
    """Return the outputs that differ from what the source generates."""
    return [path for path, text in outputs().items()
            if not path.exists() or path.read_text() != text]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if any output is stale")
    opts = parser.parse_args(argv)

    if opts.check:
        stale = check()
        for path in stale:
            print(f"stale: {path.relative_to(REPO)} (run scripts/gen_command_dictionary.py)")
        return 1 if stale else 0

    for path, text in outputs().items():
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
