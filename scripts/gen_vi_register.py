@dataclass
class Item:
    ident: str
    source: str
    line: int
    test: str
    criterion: str
    verifies: str
    when: str
    owner: str = ""
    event: str = ""
    date: str = ""
    sort_date: Optional[date] = None
    rids: List[str] = field(default_factory=list)
    status: str = "Open"
    also: List[str] = field(default_factory=list)
    note: str = ""


@dataclass
class Action:
    ident: str
    action: str
    owner: str
    due: str
    criterion: str
    rids: str
    status: str
    line: int


def plain(text: str) -> str:
    """Cell text safe in the register: links to their text, no code or bold marks, no TBD/TBR words."""
    text = LINK.sub(r"\1", text).replace("`", "").replace("**", "")
    text = TBX.sub("(open)", text)
    return re.sub(r"\s+", " ", text).strip().replace("|", "\\|")


def cells(row: str) -> List[str]:
    return [c.strip() for c in re.split(r"(?<!\\)\|", row.strip().strip("|"))]


def documents(root: Path) -> Iterable[Path]:
    for top in ROOTS:
        base = root / top
        if not base.exists():
            continue
        for path in sorted(base.rglob("*.md")):
            rel = path.relative_to(root).as_posix()
            if any(part.startswith(".") for part in path.relative_to(root).parts):
                continue
            if any(rel == ex or rel.startswith(ex) for ex in EXCLUDED):
                continue
            yield path


def column(header: List[str], *names: str) -> Optional[int]:
    for index, name in enumerate(header):
        low = name.lower()
        if any(n in low for n in names):
            return index
    return None


def parse_items(root: Path) -> Tuple[List[Item], List[str]]:
    items: List[Item] = []
    problems: List[str] = []
    for path in documents(root):
        rel = path.relative_to(root).as_posix()
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        header: Optional[List[str]] = None
        seen: Dict[str, int] = {}
        in_fence = False
        for n, line in enumerate(lines, 1):
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence or not line.startswith("|"):
                continue
            if n < len(lines) and SEPARATOR.match(lines[n].strip()):
                header = cells(line)
                continue
            m = ROW.match(line)
            if not m or header is None:
                continue
            ident = m.group(1)
            if ident in seen:
                problems.append(f"{rel}:{n}: {ident} defined twice in this document (first at line {seen[ident]})")
                continue
            seen[ident] = n
            row = cells(line)
            get = lambda i: row[i] if i is not None and i < len(row) else ""  # noqa: E731
            i_test = column(header, "test", "item", "verification", "what it")
            i_pass = column(header, "pass")
            i_ver = column(header, "verifies")
            i_when = column(header, "when", "event")
            i_art = column(header, "article")
            i_own = column(header, "owner")
            test = get(i_test)
            criterion = get(i_pass)
            if i_pass is not None and i_pass == i_test:     # "Test and pass criterion" in one cell
                head, sep, tail = test.partition("Pass:")
                criterion = tail if sep else test
                test = head if sep else test
            elif i_pass is None and i_test is not None:
                criterion = ""
            if column(header, "what it") is not None:        # LBA: "what it replaces" | "test and pass criterion"
                combined = get(column(header, "test and pass"))
                head, sep, tail = combined.partition("Pass:")
                test, criterion = (head, tail) if sep else (combined, combined)
            art = get(i_art) if i_art != i_when else ""
            when = get(i_when) if art.strip() == get(i_when).strip() else " ".join(x for x in (art, get(i_when)) if x)
            owner = plain(get(i_own)) or OWNERS.get(rel, "Systems engineer")
            items.append(Item(ident, rel, n, plain(test), plain(criterion), plain(get(i_ver)), plain(when),
                              owner=owner))
    return items, problems


def parse_actions(root: Path) -> Tuple[List[Action], List[str]]:
    path = root / SCHEDULE
    actions: List[Action] = []
    problems: List[str] = []
    if not path.exists():
        return actions, problems
    header: Optional[List[str]] = None
    lines = path.read_text(encoding="utf-8").splitlines()
    for n, line in enumerate(lines, 1):
        if not line.startswith("|"):
            continue
        if n < len(lines) and SEPARATOR.match(lines[n].strip()):
            header = [h.lower() for h in cells(line)]
            continue
        m = DA_ROW.match(line)
        if not m or header is None:
            continue
        row = cells(line)
        val = {name: (row[i] if i < len(row) else "") for i, name in enumerate(header)}
        act = Action(m.group(1), plain(val.get("decision or action", "")), plain(val.get("owner", "")),
                     plain(val.get("due", "")), plain(val.get("pass criterion or outcome", "")),
                     plain(val.get("parent rid", "")), plain(val.get("status", "")), n)
        if not act.owner:
            problems.append(f"{SCHEDULE}:{n}: {act.ident} has no owner")
        if not ISO.search(act.due):
            problems.append(f"{SCHEDULE}:{n}: {act.ident} has no due date (YYYY-MM-DD)")
        if not act.criterion:
            problems.append(f"{SCHEDULE}:{n}: {act.ident} has no pass criterion or outcome")
        actions.append(act)
    return actions, problems


def schedule_events(root: Path) -> Tuple[Dict[str, Tuple[str, date]], date]:
    """Event code -> (date text, sort date), from the critical-path model at its defaults."""
    pm = root / "software/simulation/cdr/pm"
    sys.path.insert(0, str(pm if (pm / "schedule_cpm.py").exists() else REPO / "software/simulation/cdr/pm"))
    import schedule_cpm as cpm  # noqa: E402
    launch = date(2028, 11, 1)
    by = cpm.solve(cpm.tasks(False, launch=launch), launch - timedelta(days=50))
    out: Dict[str, Tuple[str, date]] = {}
    for code, (_, task, mode) in EVENT_TASKS.items():
        if mode == "integration":
            d = launch - timedelta(days=47)
            out[code] = (d.isoformat(), d)
        elif mode == "orbit":
            out[code] = (f"after launch ({launch.isoformat()})", launch)
        else:
            t = by[task]
            s, f = cpm.day(t.es), cpm.day(t.ef)
            if mode == "start":
                out[code] = (f"by {s.isoformat()}", s)
            elif mode == "finish":
                out[code] = (f.isoformat(), f)
            else:
                out[code] = (f"{s.isoformat()} to {f.isoformat()}", s)
    return out, launch


def l_minus(launch: date, value: float, unit: str) -> date:
    if unit.lower().startswith("d"):
        return launch - timedelta(days=round(value))
    sys.path.insert(0, str(REPO / "software/simulation/cdr/pm"))
    import schedule_cpm as cpm  # noqa: E402
    return cpm.months_before(launch, value)


def resolve(items: List[Item], events: Dict[str, Tuple[str, date]], launch: date) -> List[str]:
    problems: List[str] = []
    by_id: Dict[str, Item] = {}
    for it in items:
        by_id.setdefault(it.ident, it)

    def direct(it: Item) -> Optional[Tuple[str, str, date]]:
        ov = OVERRIDES.get(it.ident, {})
        if "event" in ov:
            ev = ov["event"]
            if ISO.fullmatch(ev):
                return ("date", ev, date.fromisoformat(ev))
            text, d = events[ev]
            return (ev, text, d)
        found: List[Tuple[date, str, str]] = []
        dates = sorted(date.fromisoformat(iso) for iso in ISO.findall(it.when))
        if dates:       # a date written in the defining document wins over the event words around it
            return ("date", dates[0].isoformat(), dates[0])
        for m in LREL.finditer(it.when):
            d = l_minus(launch, float(m.group(1)), m.group(2))
            found.append((d, f"L-{m.group(1)} {m.group(2)[0].upper()}", d.isoformat()))
        low = it.when.lower()
        for pattern, code in WHEN_RULES:
            if re.search(pattern, low):
                text, d = events[code]
                found.append((d, code, text))
        if not found:
            return None
        d, code, text = min(found, key=lambda f: f[0])
        return (code, text, d)

    pending: List[Item] = []
    for it in items:
        r = direct(it)
        if r:
            it.event, it.date, it.sort_date = r
        else:
            pending.append(it)
    for _ in range(3):      # "with VI-x" / "after VI-x": take the other item's event
        for it in list(pending):
            refs = re.findall(ITEM_ID, it.when)
            hit = next((by_id[r] for r in refs if r in by_id and by_id[r].sort_date), None)
            if hit:
                it.event, it.date, it.sort_date = hit.event, f"{hit.date} (with {hit.ident})", hit.sort_date
                pending.remove(it)
    for it in pending:
        problems.append(f"{it.source}:{it.line}: {it.ident} has no dated event (when: '{it.when or 'none'}')")
    for it in items:
        ov = OVERRIDES.get(it.ident, {})
        if "criterion" in ov:
            it.criterion = plain(ov["criterion"])
        if "owner" in ov:
            it.owner = ov["owner"]
        if "status" in ov:
            it.status = plain(ov["status"])
        if ov:
            it.note = plain(ov.get("why", ""))
        if not it.criterion:
            problems.append(f"{it.source}:{it.line}: {it.ident} has no pass criterion")
    return problems


def expand_ids(text: str) -> List[str]:
    """Item IDs cited in a RID's text, with ranges and lists expanded: VI-RFB-01..09, VI-01 to VI-06,
    VI-RF-01, 03, 08."""
    out: List[str] = []
    for m in re.finditer(r"\b((?:VI|V)-(?:[A-Z0-9]+-)*)(\d{1,2})((?:\s*(?:\.\.|to|–|-)\s*(?:(?:VI|V)-(?:[A-Z0-9]+-)*)?\d{1,2})"
                         r"|(?:,\s*\d{1,2}\b)+)?", text):
        prefix, first, rest = m.group(1), m.group(2), m.group(3) or ""
        width = len(first)
        out.append(prefix + first)
        if not rest:
            continue
        rng = re.match(r"\s*(?:\.\.|to|–|-)\s*(?:(?:VI|V)-(?:[A-Z0-9]+-)*)?(\d{1,2})", rest)
        if rng:
            for k in range(int(first) + 1, int(rng.group(1)) + 1):
                out.append(f"{prefix}{k:0{width}d}")
        else:
            out.extend(f"{prefix}{int(k):0{width}d}" for k in re.findall(r"\d{1,2}", rest))
    out.extend(re.findall(r"\bAV-V\d+\b", text))
    for m in re.finditer(r"\bRAD-V(\d+)(?:\s*(?:\.\.|to|–)\s*(?:RAD-)?V(\d+))?\b", text):   # RAD-V1 to V6
        last = int(m.group(2) or m.group(1))
        out.extend(f"RAD-V{k}" for k in range(int(m.group(1)), last + 1))
    return out


def rid_links(root: Path) -> Dict[str, List[str]]:
    """Item ID -> RIDs whose disposition, closure or round-3 reason cites it."""
    review = root / "software/simulation/cdr/review"
    links: Dict[str, List[str]] = {}
    if not review.exists():
        return links
    sys.path.insert(0, str(review))
    texts: List[Tuple[str, str]] = []
    try:
        from rids_round1 import RIDS  # noqa: E402
        texts += [(r[0], f"{r[2]} {r[4]}") for r in RIDS]
    except ImportError:
        pass
    try:
        from rids_status import CLOSURE  # noqa: E402
        texts += [(k, v[1]) for k, v in CLOSURE.items()]
    except ImportError:
        pass
    try:
        import rids_round3 as r3  # noqa: E402
        texts += [(k, v) for k, v in getattr(r3, "REOPEN", {}).items()]
        texts += [(r[0], f"{r[2]} {r[4]}") for r in getattr(r3, "NEW", [])]
        texts += [(k, v[1]) for k, v in getattr(r3, "FINAL3", {}).items()]
    except ImportError:
        pass
    for rid, text in texts:
        for ident in expand_ids(text):
            if rid not in links.setdefault(ident, []):
                links[ident].append(rid)
    return links


def build(root: Path) -> Tuple[List[Item], List[Action], List[str], List[str]]:
    raw, problems = parse_items(root)
    events, launch = schedule_events(root)
    problems += resolve(raw, events, launch)
    links = rid_links(root)
    merged: Dict[str, Item] = {}
    for it in raw:
        if it.ident in merged:
            merged[it.ident].also.append(it.source)
        else:
            merged[it.ident] = it
            it.rids = sorted(links.get(it.ident, []), key=rid_key)
    actions, more = parse_actions(root)
    problems += more
    defined = set(merged)
    cited = sorted({i for ids in links for i in [ids] if i not in defined}, key=item_key)
    return sorted(merged.values(), key=lambda i: (i.sort_date or date.max, item_key(i.ident))), actions, problems, cited


def rid_key(rid: str) -> Tuple[str, int]:
    head, _, num = rid.rpartition("-")
    return (head, int(num) if num.isdigit() else 0)


def item_key(ident: str) -> Tuple:
    return tuple(int(p) if p.isdigit() else p for p in re.split(r"(\d+)", ident))


def render_block(items: List[Item], actions: List[Action], cited: List[str]) -> str:
    out = [BEGIN, ""]
    by_event: Dict[str, int] = {}
    for it in items:
        by_event[it.event] = by_event.get(it.event, 0) + 1
    out += ["### 3.1 Summary (generated)", "",
            f"{len(items)} verification items defined in {len({i.source for i in items})} documents; "
            f"{sum(1 for i in items if i.status != 'Open')} closed; {len(actions)} decision points and dated actions "
            f"(`mission/SCHEDULE.md` §5).", "",
            "| First event | Items |", "|-------------|-------|"]
    names = {k: v[0] for k, v in EVENT_TASKS.items()}
    names["date"] = "Dated in the defining document"
    for code in sorted(by_event, key=lambda c: min((i.sort_date or date.max) for i in items if i.event == c)):
        label = names.get(code, code if code.startswith("L-") else code)
        out.append(f"| {label} | {by_event[code]} |")
    out += ["", "### 3.2 Verification items (generated, in order of first event)", "",
            "| ID | Test | Pass criterion | Event, date | Owner | Parent RID | Status | Defined in |",
            "|----|------|----------------|-------------|-------|------------|--------|------------|"]
    for it in items:
        where = f"`{it.source}`" + "".join(f"; also `{a}`" for a in it.also)
        crit = it.criterion + (f" *(register: {it.note})*" if it.note else "")
        owner = it.owner if it.owner.startswith("PI") else it.owner + UNNAMED
        ev = names.get(it.event, it.event)
        out.append(f"| {it.ident} | {it.test} | {crit} | {ev}: {it.date} | {owner} | "
                   f"{', '.join(it.rids) or '—'} | {it.status} | {where} |")
    out += ["", "### 3.3 Decision points and dated actions (generated from `mission/SCHEDULE.md` §5)", "",
            "| ID | Decision or action | Owner | Due | Pass criterion or outcome | Parent RID | Status |",
            "|----|--------------------|-------|-----|---------------------------|------------|--------|"]
    for a in actions:
        out.append(f"| {a.ident} | {a.action} | {a.owner} | {a.due} | {a.criterion} | {a.rids or '—'} | "
                   f"{a.status or 'Open'} |")
    out += ["", "### 3.4 Cited by a RID but not defined in a verification table (generated)", ""]
    out.append(", ".join(cited) if cited else "None.")
    out += ["", END]
    return "\n".join(out)


def splice(text: str, block: str) -> str:
    if BEGIN in text and END in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END):]
        return head + block + tail
    return text.rstrip() + "\n\n" + block + "\n"


def main(argv: Optional[List[str]] = None, root: Path = REPO) -> int:
    ap = argparse.ArgumentParser(description="Verification-item register (P3P-01)")
    ap.add_argument("--check", action="store_true", help="fail if the register is stale or an item is incomplete")
    args = ap.parse_args(argv)
    items, actions, problems, cited = build(root)
    block = render_block(items, actions, cited)
    path = root / REGISTER
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    wanted = splice(current, block)
    print(f"{len(items)} verification items, {len(actions)} dated actions, {len(problems)} problem(s), "
          f"{len(cited)} cited but not defined")
    for p in problems:
        print(("::error::" if args.check else "") + p)
    if args.check:
        if current != wanted:
            print(f"::error::{REGISTER} is stale: run python3 scripts/gen_vi_register.py")
            return 1
        return 1 if problems else 0
    path.write_text(wanted, encoding="utf-8")
    print(f"wrote {REGISTER}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
